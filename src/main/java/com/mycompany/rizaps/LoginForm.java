    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Username dan password wajib diisi!"
        );
        return;
    }

    try (org.hibernate.Session session =
            HibernateUtil.getSessionFactory().openSession()) {

        String hql = "FROM Login WHERE username = :uname AND password = :pass";

        org.hibernate.query.Query<Login> query =
                session.createQuery(hql, Login.class);

        query.setParameter("uname", username);
        query.setParameter("pass", password);

        Login user = query.uniqueResult();

        if (user != null) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Login berhasil! Selamat datang, " + username
            );
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Username atau password salah!"
            );
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Terjadi kesalahan: " + e.getMessage()
        );
        e.printStackTrace();
    }

    }//GEN-LAST:event_jButton1ActionPerformed

